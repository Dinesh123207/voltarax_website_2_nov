const test = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID, createHmac, createHash } = require('node:crypto');
const { open } = require('../db/client');
const { createCommerce } = require('../services/commerce');
const s = require('../db/schema.ts');
const env = { PAYMENTS_ENABLED: 'true', RAZORPAY_KEY_ID: 'rzp_test_Synthetic', RAZORPAY_KEY_SECRET: 'synthetic-payment-secret', RAZORPAY_WEBHOOK_SECRET: 'synthetic-webhook-secret' };
const signature = (raw, secret = env.RAZORPAY_WEBHOOK_SECRET) => createHmac('sha256', secret).update(raw).digest('hex');
const capture = (order, extra = {}) => ({ event: 'payment.captured', payload: { payment: { entity: { id: 'pay_Synthetic', order_id: order.gatewayOrderId, amount: order.amountPaise, currency: 'INR', status: 'captured', captured: true, ...extra } } } });
const refund = (id, amount) => ({ event: 'refund.processed', payload: { refund: { entity: { id, payment_id: 'pay_Synthetic', amount, currency: 'INR', status: 'processed' } } } });
const send = (service, data, eventId) => { const raw = Buffer.from(JSON.stringify(data)); return service.webhook(raw, signature(raw), eventId); };
async function setup(t) {
  const c = await open({ pglite: true, migrate: true }); t.after(() => c.close());
  let count = 0;
  const service = createCommerce(c.db, { env, createRemoteOrder: async data => ({ ...data, id: `order_Synthetic${++count}`, status: 'created' }) });
  const plan = await service.savePlan({ name: 'Synthetic invoice layout plan with an intentionally long description for a bounded test receipt', description: 'Generated test input; no product offer.', pricePaise: 10000, active: true }, 'admin');
  const order = await service.createOrder({ planId: plan.id, planVersion: plan.version, requestKey: randomUUID() }, 'buyer');
  return { c, service, order };
}
test('valid browser signature is only a hint; verified capture atomically creates one payment/invoice under replay', async t => {
  const { c, service, order } = await setup(t);
  const callback = { razorpay_order_id: order.gatewayOrderId, razorpay_payment_id: 'pay_Synthetic', razorpay_signature: signature(`${order.gatewayOrderId}|pay_Synthetic`, env.RAZORPAY_KEY_SECRET) };
  await assert.rejects(service.verifyCallback(order.id, 'other', callback), error => error.status === 404);
  await assert.rejects(service.verifyCallback(order.id, 'buyer', { ...callback, razorpay_payment_id: 'pay_Tampered' }), error => error.status === 401);
  assert.equal((await service.verifyCallback(order.id, 'buyer', callback)).confirmed, false);
  assert.equal((await service.order(order.id, 'buyer')).status, 'pending');
  await assert.rejects(service.invoice(order.id, 'buyer'), error => error.status === 404);
  const event = capture(order), raw = Buffer.from(JSON.stringify(event));
  await assert.rejects(service.webhook(Buffer.concat([raw, Buffer.from(' ')]), signature(raw)), error => error.status === 401);
  const results = await Promise.all([send(service, event, 'event_capture1'), send(service, event, 'event_capture1')]);
  assert.equal(results.filter(row => row.duplicate).length, 1);
  assert.equal((await service.order(order.id, 'buyer')).status, 'paid');
  assert.equal((await c.db.select().from(s.commercePayments)).length, 1);
  const invoice = await service.invoice(order.id, 'buyer'), pdf = Buffer.from(invoice.pdfBase64, 'base64');
  assert.equal(pdf.subarray(0, 4).toString(), '%PDF'); assert.equal(createHash('sha256').update(pdf).digest('hex'), invoice.sha256);
  assert.equal(invoice.evidence.gst, null); assert.equal(invoice.evidence.mode, 'test');
  require('node:fs').writeFileSync(require('node:path').resolve(__dirname, '../../../docs/test-results/phase07-invoice-layout-fixture.pdf'), pdf);
  await assert.rejects(service.invoice(order.id, 'other'), error => error.status === 404);
  await send(service, { ...event, synthetic_replay_variant: true }, 'event_capture2');
  assert.equal((await c.db.select().from(s.commerceInvoices)).length, 1);
  assert.equal((await service.details(order.id, 'buyer')).invoice.sha256, invoice.sha256);
});
test('signed mismatched amounts and unconfirmed events cannot mark an order paid', async t => {
  const { c, service, order } = await setup(t);
  await send(service, { event: 'payment.authorized', payload: {} }, 'event_authorized');
  assert.equal((await service.order(order.id, 'buyer')).status, 'pending');
  assert.equal((await send(service, capture(order, { amount: order.amountPaise + 1 }), 'event_wrong_amount')).result, 'review_required');
  assert.equal((await service.order(order.id, 'buyer')).status, 'review_required');
  await assert.rejects(service.createOrder({ planId: order.planId, planVersion: order.planSnapshot.version, requestKey: randomUUID() }, 'buyer'), error => error.status === 409);
  assert.equal((await c.db.select().from(s.commercePayments)).length, 0);
  assert.equal((await c.db.select().from(s.commerceInvoices)).length, 0);
  await assert.rejects(send(service, capture(order, { currency: 'USD' }), 'event_wrong_currency'), error => error.status === 422);
});
test('out-of-order refunds retry, manual requests do not move funds and signed refunds have no second effect', async t => {
  const { c, service, order } = await setup(t);
  const early = refund('rfnd_Synthetic1', 4000);
  await assert.rejects(send(service, early, 'event_refund1'), error => error.status === 503);
  assert.equal((await c.db.select().from(s.commerceEvents)).length, 0);
  await send(service, capture(order), 'event_capture');
  const request = { requestId: randomUUID(), amountPaise: 4000, note: 'Synthetic manual refund review' };
  const record = await service.requestRefund(order.id, request, 'admin');
  assert.equal((await service.requestRefund(order.id, request, 'admin')).id, record.id);
  assert.equal((await service.details(order.id, 'buyer')).payment.refundedPaise, 0);
  await assert.rejects(service.requestRefund(order.id, { ...request, requestId: randomUUID(), amountPaise: 7000 }, 'admin'), error => error.status === 422);
  await service.updateRefund(order.id, record.id, { status: 'submitted', gatewayRefundId: 'rfnd_Synthetic1' }, 'admin');
  await assert.rejects(service.updateRefund(order.id, record.id, { status: 'submitted', gatewayRefundId: 'rfnd_Tampered' }, 'admin'), error => error.status === 409);
  await send(service, early, 'event_refund1');
  await send(service, { ...early, synthetic_replay_variant: true }, 'event_refund2');
  let detail = await service.details(order.id, 'buyer'); assert.equal(detail.payment.refundedPaise, 4000); assert.equal(detail.order.status, 'paid');
  await send(service, refund('rfnd_Synthetic2', 6000), 'event_refund3');
  detail = await service.details(order.id, 'buyer'); assert.equal(detail.payment.refundedPaise, 10000); assert.equal(detail.order.status, 'refunded');
  assert.equal(detail.refunds.filter(row => row.status === 'processed').length, 2);
});
test('receipt-based test reconciliation binds an uncertain order but never invents payment confirmation', async t => {
  const c = await open({ pglite: true, migrate: true }); t.after(() => c.close()); let remote;
  const service = createCommerce(c.db, { env, createRemoteOrder: async data => { remote = { ...data, id: 'order_Reconciled', status: 'paid' }; throw Error('Synthetic lost response'); }, fetchRemoteOrder: async () => remote });
  const plan = await service.savePlan({ name: 'Synthetic reconciliation', description: '', pricePaise: 100, active: true }, 'admin');
  await assert.rejects(service.createOrder({ planId: plan.id, planVersion: plan.version, requestKey: randomUUID() }, 'buyer'));
  const order = (await service.orders('buyer'))[0];
  const original = remote.receipt; remote.receipt = 'foreign';
  await assert.rejects(service.reconcile(order.id, 'order_Reconciled', 'admin'), error => error.status === 422);
  remote.receipt = original;
  assert.equal((await service.reconcile(order.id, 'order_Reconciled', 'admin')).status, 'pending');
  await assert.rejects(service.invoice(order.id, 'buyer'), error => error.status === 404);
});
